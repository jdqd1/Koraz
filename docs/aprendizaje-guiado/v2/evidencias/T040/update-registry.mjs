import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { createHash } from 'node:crypto';
import { resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
const here=fileURLToPath(new URL('./',import.meta.url)),root=resolve(here,'../../../../..');
const path='docs/aprendizaje-guiado/v2/registro-ejecucion.json',target=resolve(root,path);
const read=name=>JSON.parse(readFileSync(resolve(here,name),'utf8'));
const hash=data=>createHash('sha256').update(data).digest('hex');
const before=readFileSync(target,'utf8'), baseline=read('baseline.json');
if(hash(before)!==baseline.files.find(f=>f.path===path)?.sha256) throw new Error('Registry changed since T040 baseline; preserve concurrent edits');
if(existsSync(resolve(here,'registry.before.json'))) throw new Error('Do not overwrite registry backup');
const old=JSON.parse(before), next=structuredClone(old), task=next.tasks.find(t=>t.taskId==='T040');
if(!task) throw new Error('T040 registry entry missing');
const counts=read('counts-and-omissions.json'),api=counts['api-effective'],guided=counts['guided-v2-effective'],legacy=counts['legacy-effective'];
const technical=api.failed===0 && guided.failed===0 && read('regression-final-load.json').status==='PASS' && counts['large-editor-effective']?.stats.expected===2 && counts['large-editor-effective']?.stats.unexpected===0;
task.status=!technical?'FAIL LOCAL':legacy.failed?'PARCIAL LOCAL':'PASS LOCAL';
task.evidence=['docs/aprendizaje-guiado/v2/evidencias/T040/README.md','docs/aprendizaje-guiado/v2/evidencias/T040/result.json','docs/aprendizaje-guiado/v2/evidencias/T040/counts-and-omissions.json'];
task.issues=legacy.failed?[{code:'PREEXISTING_LEGACY_VIDEO_TESTS',count:legacy.failed,status:'FAIL PREEXISTENTE; reparación de expectativas pendiente de autorización'}]:[];
task.baseSha=baseline.baseSha; task.recordedUtc=new Date().toISOString(); task.nextTaskStarted=false;
task.nextTaskIds=legacy.failed?['T040']:['T041'];
const eol=before.includes('\r\n')?'\r\n':'\n';
const block=value=>JSON.stringify(value,null,2).split('\n').map(line=>'    '+line).join(eol);
const oldBlock=block(old.tasks.find(t=>t.taskId==='T040'));
if(before.indexOf(oldBlock)<0 || before.indexOf(oldBlock)!==before.lastIndexOf(oldBlock)) throw new Error('Cannot isolate exact T040 block');
const after=before.replace(oldBlock,block(task));
const withoutTask=value=>({...value,tasks:value.tasks.filter(t=>t.taskId!=='T040')});
if(JSON.stringify(withoutTask(old))!==JSON.stringify(withoutTask(JSON.parse(after)))) throw new Error('Other registry entries would change');
writeFileSync(resolve(here,'registry.before.json'),before); writeFileSync(target,after);
writeFileSync(resolve(here,'registry-mutation.json'),JSON.stringify({status:'PASS',authorization:'Handoff cierre por tarea: actualización del registro de ejecución',changedTaskIds:['T040'],otherEntriesPreserved:true,beforeSha256:hash(before),afterSha256:hash(after)},null,2));
console.log(`Only T040 registry entry updated: ${task.status}`);
