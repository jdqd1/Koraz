import fs from 'node:fs';
import path from 'node:path';
import crypto from 'node:crypto';
import {fileURLToPath} from 'node:url';
const out=path.dirname(fileURLToPath(import.meta.url));
const logPath=path.join(out,'execution-log.json');
const log=JSON.parse(fs.readFileSync(logPath,'utf8'));
const file=path.join(out,'ruta.koraz-route.json');
const bytes=fs.readFileSync(file), pack=JSON.parse(bytes), actualHash=crypto.createHash('sha256').update(bytes).digest('hex');
if(actualHash!==log.package.sha256)throw Error('Hash final discordante');
const guideText=fs.readFileSync(log.guide.path,'utf8');
if(!pack.sources.every(s=>guideText.includes(s.excerpt)))throw Error('Excerpt no literal');
const reserves=pack.activities.filter(a=>['final','retention7','retention30'].includes(a.use));
if(new Set(reserves.map(a=>a.equivalenceKey)).size!==3)throw Error('Reservas no disjuntas');
log.commands.push({executable:process.execPath,args:[path.join(out,'build.mjs')],exitCode:0,result:'Segunda generación completada; draft y publish portable exit 0; único aviso diagnóstico breve.'});
log.commands.push({executable:process.execPath,args:[path.join(out,'finalize-log.mjs')],exitCode:1,result:'Primer intento de cierre: ENOENT por pathname URL codificado con %20; no modificó archivos. Se corrigió con fileURLToPath.'});
log.commands.push({executable:process.execPath,args:[path.join(out,'finalize-log.mjs')],exitCode:0,result:'Hash final confirmado, tres excerpts literales, tres familias reservadas exclusivas. Registro final completado.'});
log.validations.push({check:'exact-package-hash-and-source-excerpts',status:'PASS',sha256:actualHash,sourceExcerpts:3,reserveFamilies:3});
log.writes.push('finalize-log.mjs','round-1-ruta.koraz-route.json','round-1-validation-draft.json','round-1-validation-publish.json');
fs.writeFileSync(logPath,JSON.stringify(log,null,2)+'\n');
console.log(JSON.stringify({status:'PASS',sha256:actualHash,files:fs.readdirSync(out)}));
