import{readFileSync,writeFileSync,existsSync,statSync}from'node:fs';
import{createHash}from'node:crypto';
import{spawnSync}from'node:child_process';
import{fileURLToPath}from'node:url';
import assert from'node:assert/strict';
const here=new URL('./',import.meta.url),root=fileURLToPath(new URL('../../../../../',here));
const read=(n)=>JSON.parse(readFileSync(new URL(n,here),'utf8').replace(/^\uFEFF/,''));
const hash=p=>createHash('sha256').update(readFileSync(root+p)).digest('hex');
const baseline=read('baseline.json'),authorization=read('scope-authorization.json');
assert.equal(authorization.answer,'Sí, autorizar esta corrección mínima');
const allowed=new Set(['tools/skills/crear-rutas-koraz/references/pedagogia.md','tools/skills/crear-rutas-koraz/references/contrato-koraz-2.0.md',authorization.additionalFile]);
const changed=baseline.files.filter(f=>!existsSync(root+f.path)||hash(f.path)!==f.sha256).map(f=>({path:f.path,originalSha256:f.sha256,currentSha256:existsSync(root+f.path)?hash(f.path):null}));
assert(changed.every(f=>allowed.has(f.path)),JSON.stringify(changed.filter(f=>!allowed.has(f.path))));
const git=(...args)=>{const r=spawnSync('git',args,{cwd:root,encoding:'utf8'});assert.equal(r.status,0,r.stderr);return r.stdout;};
const paths=git('ls-files','--cached','--others','--exclude-standard','-z').split('\0').filter(Boolean);
const baselinePaths=new Set(baseline.files.map(f=>f.path));
const additions=paths.filter(p=>!baselinePaths.has(p)&&!p.startsWith('docs/aprendizaje-guiado/v2/evidencias/T045/'));
assert.equal(additions.length,0,JSON.stringify(additions));
const frozen=JSON.parse(readFileSync(root+'docs/aprendizaje-guiado/v2/evidencias/T042/accepted-contract-hashes.json','utf8'));
for(const f of frozen.hashes)assert.equal(hash(f.path),f.sha256,f.path);
const diff=git('diff','--check');assert.equal(diff,'');
const status=git('status','--short');
const report={status:'PASS',baselineFiles:baseline.files.length,protectedFilesUnchanged:baseline.files.length-changed.length,changed,additionalFilesOutsideAllowlist:[],frozenFilesUnchanged:frozen.hashes.length,gitDiffCheck:true,statusShort:status,authorization:'scope-authorization.json',nextTaskStarted:false};
writeFileSync(new URL('scope-check.json',here),JSON.stringify(report,null,2)+'\n');
console.log(JSON.stringify({status:report.status,protectedFilesUnchanged:report.protectedFilesUnchanged,changed:changed.length,frozen:frozen.hashes.length}));
