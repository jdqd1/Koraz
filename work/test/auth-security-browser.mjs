  assert.ok(!page.url().includes("acceder"));
  results.browserRestartPersistence = true;
  await page.goto(origin + "/dashboard/seguridad");
  await page.getByLabel("Contraseña actual", { exact: true }).fill(password);
  await page.getByRole("button", { name: "Cerrar todas las sesiones" }).click();
  await page.waitForURL("**/acceder?mensaje=sesiones-cerradas", { timeout: 30000 });
